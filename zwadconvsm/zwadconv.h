// A SideDef, defining the visual appearance of a wall,
// by setting textures and offsets.
typedef struct
{
	short 		textureoffset;
	short 		rowoffset;
	char		toptexture[8];
	char		bottomtexture[8];
	char		midtexture[8];
	// Front sector, towards viewer.
	short 		sector;
} mapsidedef_t;

// A LineDef, as used for editing, and as input
// to the BSP builder.
typedef struct
{
	WORD 		v1;
	WORD 		v2;
	WORD 		flags;
	WORD 		special;
	WORD 		tag;
	WORD 		sidenum[2];
} maplinedef_t;

// [RH] Hexen-compatible LineDef.
typedef struct
{
	WORD		v1;
	WORD		v2;
	WORD		flags;
	UBYTE		special;
	UBYTE		args[5];
	WORD		sidenum[2];
} maplinedef2_t;


