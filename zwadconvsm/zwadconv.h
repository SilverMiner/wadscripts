// Sector definition, from editing.
typedef struct
{
	WORD 		floorheight;
	WORD 		ceilingheight;
	UBYTE		floorpic[8];
	UBYTE		ceilingpic[8];
	WORD 		lightlevel;
	WORD 		special;
	UWORD 		tag;
} mapsector_t;

// SubSector, as generated by BSP.
typedef struct
{
	WORD 		numsegs;
	// Index of first one, segs are stored sequentially.
	WORD 		firstseg;
} mapsubsector_t;


// LineSeg, generated by splitting LineDefs
// using partition lines selected by BSP builder.
typedef struct
{
	WORD 		v1;
	WORD 		v2;
	WORD 		angle;
	WORD 		linedef;
	WORD 		side;
	WORD 		offset;
} mapseg_t;



// BSP node structure.

// Indicate a leaf.
#define NF_SUBSECTOR	0x8000

typedef struct
{
	// Partition line from (x,y) to x+dx,y+dy)
	WORD 		x;
	WORD 		y;
	WORD 		dx;
	WORD 		dy;

	// Bounding box for each child,
	// clip against view frustum.
	WORD 		bbox[2][4];

	// If NF_SUBSECTOR its a subsector,
	// else it's a node of another subtree.
	UWORD		children[2];

} mapnode_t;

// Thing definition, position, orientation and type,
// plus skill/visibility flags and attributes.
typedef struct
{
	WORD		x;
	WORD		y;
	WORD		angle;
	WORD		type;
	WORD		options;
} mapthing_t;

// [RH] Hexen-compatible MapThing.
typedef struct
{
	UWORD		thingid;
	WORD		x;
	WORD		y;
	WORD		z;
	WORD		angle;
	WORD		type;
	WORD		flags;
	UBYTE		special;
	UBYTE		args[5];
} mapthing2_t;


